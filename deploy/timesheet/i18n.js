  function getLang() {
    try { localStorage.setItem(LANG_KEY, "en"); } catch (_) { /* ignore */ }
    return "en";
  }

  function setLang() {
    try { localStorage.setItem(LANG_KEY, "en"); } catch (_) { /* ignore */ }
    applyDocumentLang("en");
    return "en";
  }

  function toggleLang() {
    return setLang();
  }

  function t(key, vars, lang) {
    const L = "en";
    const pack = dict.en;
    let val = pack[key] || key;
    if (vars && typeof vars === "object") {
      Object.keys(vars).forEach((k) => {
        val = String(val).replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return val;
  }

  function applyDocumentLang() {
    const html = document.documentElement;
    html.lang = "en";
    html.dir = "ltr";
    document.body?.classList.remove("tc-rtl");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (!el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
        else el.textContent = val;
      } else if (el.children.length > 0) {
        // Never wipe dynamic containers (e.g. generated label previews) via textContent
        return;
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });

    document.querySelectorAll("[data-i18n-value]").forEach((el) => {
      el.value = t(el.getAttribute("data-i18n-value"));
    });
  }

  function roleLabelI18n(role) {
    const r = typeof normalizeRole === "function" ? normalizeRole(role) : String(role || "");
    return t("role_" + r) || r;
  }

  // global helper
  if (typeof window !== "undefined") {
    window.t = t;
    window.tcLang = getLang;
  }

  return { getLang, setLang, toggleLang, t, applyDocumentLang, roleLabelI18n, LANG_KEY, dict };
